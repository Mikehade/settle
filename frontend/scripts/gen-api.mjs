// Generates src/lib/api/schema.d.ts from the backend OpenAPI schema.
//
//   pnpm gen:api                      reads $OPENAPI_URL, or http://localhost:8000/openapi.json
//   pnpm gen:api ./openapi.json       reads a saved schema file instead
//
// The WebSocket contract is not part of OpenAPI; its event types are written by hand.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

const source = process.argv[2] ?? process.env.OPENAPI_URL ?? "http://localhost:8000/openapi.json";
const output = new URL("../src/lib/api/schema.d.ts", import.meta.url);
const EM_DASH = String.fromCharCode(0x2014);

const schema = /^https?:\/\//.test(source)
  ? new URL(source)
  : JSON.parse(await readFile(resolve(source), "utf8"));

// Fields with a server-side default stay optional, so request bodies can leave them out
// (PUT /policy relies on that for partial updates).
const ast = await openapiTS(schema, { defaultNonNullable: false });

// Backend docstrings use em dashes; the house style does not, so plain hyphens go in instead.
const body = astToString(ast).replaceAll(EM_DASH, "-");
const banner = `// Generated by \`pnpm gen:api\` from the backend OpenAPI schema. Do not edit by hand.\n\n`;

await writeFile(output, banner + body);
console.log(`Wrote ${output.pathname} from ${source}`);
